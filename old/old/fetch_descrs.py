import requests
import csv

def get_game_description(game_id, token):
    url = f"https://db.hfsplay.fr/api/v1/games/{game_id}"
    headers = {'Authorization': f'Bearer {token}'}
    response = requests.get(url, headers=headers)

    if response.status_code == 200:
        game_data = response.json()
        description_fr = game_data.get('description_fr', '')
        description_en = game_data.get('description_en', '')
        return game_id, description_fr, description_en
    else:
        print(f'Failed to retrieve game data for ID {game_id}')
        return game_id, '', ''

def save_to_csv(data, filename):
    with open(filename, 'w', newline='', encoding='utf-8') as file:
        writer = csv.writer(file)
        writer.writerow(['game_id', 'description_fr', 'description_en'])  # Header
        writer.writerows(data)

